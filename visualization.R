# ==============================================================================
# [新增] 全局绘图主题设置 (统一定义，方便修改)
# ==============================================================================
# 基础字号设为 14，让整体文字变大
base_theme <- theme_bw(base_size = 14) +
  theme(
    # --- 标题设置 ---
    plot.title = element_text(face = "bold", size = 16, hjust = 0), # 图标题加粗加大
    axis.title = element_text(face = "bold", size = 14),            # 轴标题加粗
    
    # --- 分面标签设置 ---
    strip.background = element_rect(fill = "grey90", color = "black"), # 统一背景色
    strip.text = element_text(face = "bold", size = 13),               # 分面文字加大加粗
    
    # --- 图例设置 ---
    legend.position = "bottom",
    legend.title = element_text(face = "bold", size = 13),
    legend.text = element_text(size = 11)
  )

# ==============================================================================
# 3. 绘图 A: Feature Importance Score (上半部分 - 高清版)
# ==============================================================================
pd <- position_dodge(width = 0.5)

p_score <- ggplot() +
  # --- 基准线 (加粗，颜色加深) ---
  geom_hline(data = df_baseline_sub,
             aes(yintercept = Score_Mean),
             linetype = "dashed", color = "#525252", alpha = 0.8, linewidth = 0.7) +
  
  # --- 误差棒 (加粗，且不显示图例以便合并) ---
  geom_errorbar(data = df_main_sub, 
                aes(x = Truncation_level, ymin = Score_Lower, ymax = Score_Upper, color = Method, group = Method),
                width = 0.3, alpha = 0.6, position = pd, linewidth = 0.8,
                show.legend = FALSE) + # <--- 关键：隐藏误差棒图例
  
  # --- 折线和点 (加粗加大) ---
  geom_line(data = df_main_sub, 
            aes(x = Truncation_level, y = Score_Mean, color = Method, group = Method),
            position = pd, linewidth = 1.0, alpha = 0.9) +
  geom_point(data = df_main_sub, 
             aes(x = Truncation_level, y = Score_Mean, color = Method, group = Method),
             position = pd, size = 2.5) +
  
  # --- 分面 ---
  facet_wrap(~ Feature, scales = "free_y", ncol = 3) +
  
  # --- 应用增强主题 ---
  base_theme +
  labs(y = "Importance Score", 
       color = "Imputation Method", # 显式指定图例标题
       title = "A. Sensitivity Analysis of Feature Importance Scores (XGBoost)") + 
  
  # --- A图特有主题调整 ---
  theme(
    axis.title.x = element_blank(), # 去掉X轴标题
    axis.text.x = element_blank(),  # 去掉X轴文字
    axis.ticks.x = element_blank(),
    legend.position = "none"        # 隐藏图例(交给拼图合并)
  )

# ==============================================================================
# 4. 绘图 B: Selection Probability (下半部分 - 高清版)
# ==============================================================================
p_selection <- ggplot() +
  # --- 基准线 (加粗) ---
  geom_hline(data = df_baseline_sub,
             aes(yintercept = Selection),
             linetype = "longdash", color = "#525252", linewidth = 0.7, alpha = 0.8) +
  
  # --- 折线和点 (加粗加大) ---
  geom_line(data = df_main_sub, 
            aes(x = Truncation_level, y = Selection, color = Method, group = Method),
            position = pd, linewidth = 1.0, alpha = 0.9) +
  geom_point(data = df_main_sub, 
             aes(x = Truncation_level, y = Selection, color = Method, group = Method),
             position = pd, size = 2.5) +
  
  # --- 分面与标度 ---
  facet_wrap(~ Feature, scales = "fixed", ncol = 3) + 
  scale_y_continuous(limits = c(0, 1.05), breaks = seq(0, 1, 0.2)) +
  
  # --- 应用增强主题 ---
  base_theme +
  labs(y = "Selection Probability",
       x = "Censoring Level", 
       color = "Imputation Method", # 显式指定图例标题
       title = "B. Stability of Feature Selection Probability (XGBoost)") + 
  
  # --- B图特有主题调整 ---
  theme(
    axis.text.x = element_text(angle = 45, hjust = 1, color = "black") # X轴文字倾斜且加深颜色
  )

