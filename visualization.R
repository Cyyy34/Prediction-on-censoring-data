# 定义映射表 (保持不变)
rename_map <- c(
  "U3CC07"      = "U3CC07 *",
  "U3CD07"      = "U3CD07 †",
  "Height"      = "Height *†",
  "BMI"         = "BMI *†",
  "SFLT1_V1"    = "SFLT1_V1 *",
  "fbHCG_V1"    = "fbHCG_V1 *†",
  "V2BA01_KG"   = "V2BA01_KG *",
  "Age_at_V1"   = "Age_at_V1 *†",
  "ADAM12_V1"   = "ADAM12_V1 †",
  "AFP_V1"      = "AFP_V1",
  "PLGF_V1"     = "PLGF_V1 †",
  "INHIBINA_V1" = "INHIBINA_V1 *",
  "U2BB02"      = "U2BB02 *",
  "PAPPA_V1"    = "PAPPA_V1 *†",
  "SFLT1_V2"    = "SFLT1_V2"
)

# 应用重命名
apply_rename <- function(x, map) {
  out <- map[x]
  ifelse(is.na(out), x, out)
}

df_main$Feature <- trimws(as.character(df_main$Feature))
df_baseline$Feature <- trimws(as.character(df_baseline$Feature))

df_main$Feature <- apply_rename(df_main$Feature, rename_map)
df_baseline$Feature <- apply_rename(df_baseline$Feature, rename_map)

# --- 核心修改：只筛选这三个变量 ---
target_features <- c("Height *†", "U2BB02 *", "AFP_V1")

df_main_sub <- df_main %>% filter(Feature %in% target_features)
df_baseline_sub <- df_baseline %>% filter(Feature %in% target_features)

# --- 核心修改：强制设定 Factor Level 顺序 ---
# 顺序：Height (实验组) -> U2BB02 (阳性对照) -> AFP_V1 (阴性对照)
df_main_sub$Feature <- factor(df_main_sub$Feature, levels = target_features)
df_baseline_sub$Feature <- factor(df_baseline_sub$Feature, levels = target_features)

# 设定 Method 顺序 (注意：XGBoost 包含 Raw_Trunc)
method_order <- c("Random", "Raw_Trunc", "LOD_Fill", "LOD_Half_Sub", "Gauss_Draw", 
                  "Lognorm_Draw", "MICE_Posthoc", "MICE_Trunc", "Tobit_Avg")
df_main_sub$Method <- factor(df_main_sub$Method, levels = method_order)

trunc_order <- c("L10%-R10%", "L20%-R20%", "L30%-R30%", "L40%-R40%")
df_main_sub$Truncation_level <- factor(df_main_sub$Truncation_level, levels = trunc_order)

